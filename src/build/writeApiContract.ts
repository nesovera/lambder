import { existsSync, readFileSync } from "fs";
import { dirname, resolve } from "path";
import type ts from "typescript";
import { ContractTypePrinter, type ContractPrintStyle, type PrintedContract } from "./ContractTypePrinter.js";
import { modulePathOf, type LambderModuleLocation } from "./moduleLocation.js";
import { writeFileAtomically } from "./writeFileAtomically.js";

/*
 * The contract a client compiles against, written out once as plain types.
 *
 * A client that imports `typeof lambder.ApiContract` from the server's
 * sources compiles the server to get it: every endpoint's schemas, the
 * libraries they infer through, and whatever the server's entry imports
 * besides. It also reads it as the intersection chaining built, one member
 * deep per endpoint. In a large app that is most of the client's type-check
 * time and memory, for one type. This reads the ApiContract property off the
 * exported instance and writes it out as the structure it resolves to, one
 * object type with plain members in a module that imports nothing, so the
 * client compiles the contract alone.
 *
 * What can go wrong is the file: stale against the server, or printed as
 * something other than the type it stands for. A check compares it with what
 * the server's sources print now, and a write first proves the printed type
 * the same as the server's, entry by entry, in both directions, before the
 * file is touched.
 */

type TypeScriptModule = typeof import("typescript");

const DEFAULT_HEADER = [
    "Generated by writeApiContract() from lambder/build. Do not edit.",
    "",
    "The server's API contract written out as plain types, so a client compiles",
    "the contract without compiling the server's schemas and code.",
].join("\n");

const INDENT = "    ";
/** How many compiler diagnostics a failure prints before it stops. */
const DIAGNOSTIC_LIMIT = 20;

export type LambderApiContractFileOptions = {
    /** The module that exports the Lambder instance, usually the server's entry: a path relative to the working directory, or a file URL. */
    module: LambderModuleLocation;
    /** The export that holds the instance, whose ApiContract is written out. Default: "default", the module's default export. */
    exportName?: string;
    /** The name the written module exports the contract type under. Default: "ApiContractType". */
    typeName?: string;
    /** The tsconfig.json the module compiles under, whose compiler options and path aliases resolve its imports. Relative to the working directory. Default: the nearest tsconfig.json at or above the module's directory. */
    tsconfig?: string;
    /** The TypeScript module to write. Relative to the working directory. */
    file: string;
    /** Write nothing, and answer whether the file on disk is what the contract prints now. Default: false. */
    check?: boolean;
    /** The comment the file opens with, one `//` line per line. It should name what generates the file. Default: a note naming writeApiContract(). */
    header?: string;
    /** Quotes in the generated module. Default: "double". */
    quotes?: "single" | "double";
    /** End the generated declarations and members with semicolons. Default: true. */
    semicolons?: boolean;
};

export type LambderApiContractFileResult = {
    /** False when the contract could not be read or printed, a check found the file stale, or the printed type was not the contract's. */
    ok: boolean;
    /** The absolute path. */
    file: string;
    /** How many APIs the contract holds (0 when it could not be read). */
    count: number;
    /** True when the file was (re)written; a file that already holds this text is left untouched. */
    written: boolean;
    /** APIs whose printed types differ from the file that was on disk, by name, counting the declarations each refers to. */
    changed: string[];
    added: string[];
    removed: string[];
    /** What happened, as lines to print: a summary, then one line per API that moved or per member that could not be printed. */
    lines: string[];
};

/**
 * Writes an app's API contract type to a TypeScript module as plain types,
 * or checks the one on disk, and names the APIs whose types moved.
 *
 * The contract is the ApiContract property of the instance the module
 * exports, read through the TypeScript compiler under the server's own
 * tsconfig; nothing of the server runs. Every type in it is printed as the
 * structure it resolves to: zod's inferences, mapped and conditional types and
 * the server's own types become plain object types, unions and literals. The
 * written module imports nothing, not even lambder, and exports one type
 * alias, `typeName`. Only the default library's interfaces (Date) are printed
 * by name. A non-generic named type is printed once, as a declaration of its
 * own that the entries refer to.
 *
 * Anything with no plain form fails the call and names where it sits: a
 * function, a symbol-keyed property, an enum, a class's private member, or a
 * type parameter the contract leaves open. Property `readonly` modifiers are
 * not carried over (they never decide assignability); readonly arrays and
 * tuples are.
 *
 * ```ts
 * import { writeApiContract } from "lambder/build";
 *
 * const result = await writeApiContract({
 *     module: "server/src/index.ts",   // export const lambder = initLambder()...
 *     exportName: "lambder",
 *     file: "shared/generated/apiContract.generated.ts",
 *     check: process.argv.includes("--check"),
 * });
 * console.log(result.lines.join("\n"));
 * process.exit(result.ok ? 0 : 1);
 * ```
 *
 * A check compares the text, so the file should be left out of formatters;
 * each declaration carries a `// prettier-ignore` line for Prettier. A write
 * that changes the file first compiles the new text beside the server's
 * sources and checks every entry against the contract both ways, and writes
 * nothing when one differs. The file is written to a temporary file renamed
 * over the old one, so a build reading it meanwhile never sees half of it.
 */
export const writeApiContract = async (options: LambderApiContractFileOptions): Promise<LambderApiContractFileResult> => {
    const ts = await loadTypeScript();
    const file = resolve(options.file);
    const modulePath = modulePathOf(options.module);
    const exportName = options.exportName ?? "default";
    const typeName = options.typeName ?? "ApiContractType";
    const style: ContractPrintStyle = { quote: options.quotes === "single" ? "'" : "\"", semicolon: options.semicolons === false ? "" : ";" };
    let count = 0;
    const result = (ok: boolean, written: boolean, lines: string[], moved?: ContractChanges): LambderApiContractFileResult =>
        ({ ok, file, count, written, changed: moved?.changed ?? [], added: moved?.added ?? [], removed: moved?.removed ?? [], lines });

    const project = readProject(ts, options.tsconfig, modulePath);
    if("failure" in project) return result(false, false, [`✗ ${options.module}: ${project.failure}`, ...(project.details ?? [])]);

    // The program is used for the printing alone, and dropped before the
    // verification builds its own: only the parsed files carry over.
    const printing = printContractFile(ts, project, modulePath, exportName, typeName, style, options.header);
    if("failure" in printing) return result(false, false, [`✗ ${options.module}: ${printing.failure}`, ...(printing.details ?? [])]);
    count = printing.count;
    const { text, parsedFiles } = printing;

    const previous = existsSync(file) ? readFileSync(file, "utf8") : null;
    const moved = describeContractChanges(ts, typeName, previous, text);
    const unchanged = previous !== null && previous.replace(/\r\n/g, "\n") === text;
    const movedSummary = moved.lines.length ? [`  ${moved.summary}`, ...moved.lines] : [];

    if(options.check){
        if(unchanged) return result(true, false, [`✓ ${options.file} matches the ${count} APIs of ${typeName}`], moved);
        return result(false, false, [`✗ ${options.file} is stale: regenerate it`, ...(movedSummary.length ? movedSummary : ["  no API's types changed; the header or layout did"])], moved);
    }
    if(unchanged) return result(true, false, [`✓ ${options.file} is up to date (${count} APIs)`], moved);

    const mismatches = verifyPrintedContract(ts, project, parsedFiles, { modulePath, exportName }, { file, text, typeName });
    if(mismatches.length) return result(false, false, [`✗ the printed ${typeName} is not the contract of ${exportName} in ${options.module}, so ${options.file} was not written:`, ...mismatches.map((line) => `  ${line}`)], moved);

    writeFileAtomically(file, text, previous !== null);
    return result(true, true, [`✓ Wrote ${options.file} (${count} APIs)`, ...(movedSummary.length ? movedSummary : ["  no API's types changed; the header or layout did"])], moved);
};

/** The compiler API writeApiContract reads with. TypeScript 7 ships none, so its package answers the import without one. */
const loadTypeScript = async (): Promise<TypeScriptModule> => {
    const requirement = "writeApiContract reads the contract through the TypeScript compiler API (typescript 5.4 to 6.x): install one beside lambder, such as in the generator's own package when the app is on TypeScript 7";
    let ts: TypeScriptModule;
    try {
        ts = (await import("typescript")).default;
    } catch(err) {
        throw new Error(requirement, { cause: err });
    }
    if(typeof ts?.createProgram !== "function") throw new Error(`${requirement}; the typescript installed (${(ts as { version?: string } | undefined)?.version ?? "unknown"}) has no compiler API`);
    return ts;
};

type CompiledProject = { options: ts.CompilerOptions; rootNames: string[] };
type ContractFailure = { failure: string; details?: string[] };

/** The server's compiler options, and the root files a program over the module needs: the module, and the project's own declaration files, which may declare globals the module relies on. */
const readProject = (ts: TypeScriptModule, tsconfig: string | undefined, modulePath: string): CompiledProject | ContractFailure => {
    const configPath = tsconfig ? resolve(tsconfig) : ts.findConfigFile(dirname(modulePath), ts.sys.fileExists);
    if(!configPath) return { failure: "no tsconfig.json in its directory or above it; name the server's in tsconfig" };
    const read = ts.readConfigFile(configPath, ts.sys.readFile);
    if(read.error) return { failure: `${configPath} could not be read`, details: formatDiagnostics(ts, [read.error]) };
    const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, dirname(configPath), undefined, configPath);
    if(parsed.errors.length) return { failure: `${configPath} has errors`, details: formatDiagnostics(ts, parsed.errors) };
    return {
        // Nothing is emitted, and a composite project's rule that every file be
        // listed in it does not hold for a program rooted at one module.
        options: { ...parsed.options, noEmit: true, composite: false, incremental: false, declaration: false },
        rootNames: [modulePath, ...parsed.fileNames.filter((fileName) => fileName.endsWith(".d.ts"))],
    };
};

/** An export of a module, followed through a re-export or an `export default` of a name. */
const readExport = (ts: TypeScriptModule, program: ts.Program, checker: ts.TypeChecker, modulePath: string, exportName: string): ts.Symbol | ContractFailure => {
    const sourceFile = program.getSourceFile(modulePath);
    if(!sourceFile) return { failure: "the module was not found" };
    const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
    const exported = moduleSymbol && checker.getExportsOfModule(moduleSymbol).find((symbol) => symbol.name === exportName);
    if(!exported) return { failure: `the module has no export named "${exportName}"` };
    return exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
};

/** The ApiContract of the instance a module exports, from a module that compiles. */
const readInstanceContract = (ts: TypeScriptModule, program: ts.Program, checker: ts.TypeChecker, modulePath: string, exportName: string): ts.Type | ContractFailure => {
    const sourceFile = program.getSourceFile(modulePath);
    if(!sourceFile) return { failure: "the module was not found" };
    // A module with errors can infer `any` where the contract meant a type,
    // and `any` prints and verifies as itself.
    const diagnostics = [...program.getSyntacticDiagnostics(sourceFile), ...program.getSemanticDiagnostics(sourceFile)];
    if(diagnostics.length) return { failure: "the module does not compile", details: formatDiagnostics(ts, diagnostics) };
    const instance = readExport(ts, program, checker, modulePath, exportName);
    if("failure" in instance) return { failure: `${instance.failure}; name the export that holds the Lambder instance in exportName` };
    const contract = checker.getPropertyOfType(checker.getTypeOfSymbol(instance), "ApiContract");
    if(!contract) return { failure: `"${exportName}" is not a Lambder instance: it has no ApiContract` };
    return checker.getTypeOfSymbol(contract);
};

/** The contract type a printed module exports. */
const readPrintedContract = (ts: TypeScriptModule, program: ts.Program, checker: ts.TypeChecker, file: string, typeName: string): ts.Type | ContractFailure => {
    const exported = readExport(ts, program, checker, file, typeName);
    if("failure" in exported) return exported;
    if(!(exported.flags & ts.SymbolFlags.Type)) return { failure: `${typeName} is not a type` };
    return checker.getDeclaredTypeOfSymbol(exported);
};

const printContractFile = (
    ts: TypeScriptModule,
    project: CompiledProject,
    modulePath: string,
    exportName: string,
    typeName: string,
    style: ContractPrintStyle,
    header: string | undefined,
): { text: string; count: number; parsedFiles: Map<string, ts.SourceFile> } | ContractFailure => {
    const program = ts.createProgram({ rootNames: project.rootNames, options: project.options });
    const checker = program.getTypeChecker();
    const contract = readInstanceContract(ts, program, checker, modulePath, exportName);
    if("failure" in contract) return contract;
    const printer = new ContractTypePrinter(ts, program, checker, style, typeName);
    const printed = printer.printContract(contract);
    if(printed.failures.length){
        return { failure: `${typeName} holds types with no plain form, which only the server's sources could name:`, details: printed.failures.map((line) => `  ${line}`) };
    }
    return {
        text: renderContractFile(printer, printed, typeName, style, header),
        count: printed.entries.length,
        parsedFiles: new Map(program.getSourceFiles().map((sourceFile) => [sourceFile.fileName, sourceFile])),
    };
};

const renderContractFile = (printer: ContractTypePrinter, printed: PrintedContract, typeName: string, style: ContractPrintStyle, header = DEFAULT_HEADER): string => {
    const indented = (text: string) => INDENT + text.replace(/\n/g, `\n${INDENT}`);
    const entries = printed.entries.map(({ name, text }) => indented(printer.labeledValue(`${printer.keyOf(name)}:`, text)) + style.semicolon);
    return [
        ...header.split("\n").map((line) => line ? `// ${line}` : "//"),
        "",
        // Kept as written by a formatter that honours it: a check compares
        // the text.
        "// prettier-ignore",
        entries.length ? [`export type ${typeName} = {`, ...entries, `}${style.semicolon}`].join("\n") : `export type ${typeName} = {}${style.semicolon}`,
        ...printed.declarations.flatMap(({ name, text }) => ["", "// prettier-ignore", printer.labeledValue(`type ${name} =`, text) + style.semicolon]),
        "",
    ].join("\n");
};

/**
 * Compiles the printed text beside the server's sources, from the files the
 * printing parsed, and checks each entry against the contract's in both
 * directions. Answers the entries that differ, or the diagnostics of a text
 * that does not compile; nothing when the two are the same type.
 */
const verifyPrintedContract = (
    ts: TypeScriptModule,
    project: CompiledProject,
    parsedFiles: Map<string, ts.SourceFile>,
    { modulePath, exportName }: { modulePath: string; exportName: string },
    { file, text, typeName }: { file: string; text: string; typeName: string },
): string[] => {
    const canonical = (fileName: string) => {
        const slashed = fileName.replace(/\\/g, "/");
        return ts.sys.useCaseSensitiveFileNames ? slashed : slashed.toLowerCase();
    };
    const printedFile = canonical(file);
    const isPrinted = (fileName: string) => canonical(fileName) === printedFile;
    const host = ts.createCompilerHost(project.options, true);
    const { getSourceFile, fileExists, readFile } = host;
    host.getSourceFile = (fileName, languageVersion, onError, shouldCreateNewSourceFile) => isPrinted(fileName)
        ? ts.createSourceFile(fileName, text, languageVersion, true)
        : parsedFiles.get(fileName) ?? getSourceFile.call(host, fileName, languageVersion, onError, shouldCreateNewSourceFile);
    host.fileExists = (fileName) => isPrinted(fileName) || fileExists.call(host, fileName);
    host.readFile = (fileName) => isPrinted(fileName) ? text : readFile.call(host, fileName);

    const program = ts.createProgram({ rootNames: [...project.rootNames, file], options: project.options, host });
    const printedSource = program.getSourceFile(file)!;
    const diagnostics = [...program.getSyntacticDiagnostics(printedSource), ...program.getSemanticDiagnostics(printedSource)];
    if(diagnostics.length) return ["the printed text does not compile:", ...formatDiagnostics(ts, diagnostics)];

    const checker = program.getTypeChecker();
    const contract = readInstanceContract(ts, program, checker, modulePath, exportName);
    const reprinted = readPrintedContract(ts, program, checker, file, typeName);
    if("failure" in contract) return [contract.failure];
    if("failure" in reprinted) return [`the printed text: ${reprinted.failure}`];

    const mismatches: string[] = [];
    for(const entry of checker.getPropertiesOfType(contract)){
        const counterpart = checker.getPropertyOfType(reprinted, entry.name);
        if(!counterpart){
            mismatches.push(`${entry.name}: missing from the printed type`);
            continue;
        }
        const original = checker.getTypeOfSymbol(entry);
        const copy = checker.getTypeOfSymbol(counterpart);
        if(!checker.isTypeAssignableTo(original, copy)) mismatches.push(`${entry.name}: the contract's type is not assignable to the printed one`);
        if(!checker.isTypeAssignableTo(copy, original)) mismatches.push(`${entry.name}: the printed type is not assignable to the contract's`);
    }
    for(const entry of checker.getPropertiesOfType(reprinted)){
        if(!checker.getPropertyOfType(contract, entry.name)) mismatches.push(`${entry.name}: in the printed type, not in the contract`);
    }
    return mismatches;
};

type ContractChanges = { changed: string[]; added: string[]; removed: string[]; lines: string[]; summary: string };

/**
 * Which entries a file's text and the new text print differently, counting
 * the declarations each entry refers to, directly or through another one: a
 * change to a shared named type moves every entry that uses it.
 */
const describeContractChanges = (ts: TypeScriptModule, typeName: string, previous: string | null, text: string): ContractChanges => {
    const before = previous === null ? new Map<string, string>() : entryClosures(ts, typeName, previous);
    const after = entryClosures(ts, typeName, text);
    const changed = [...after.keys()].filter((name) => before.has(name) && before.get(name) !== after.get(name));
    const added = [...after.keys()].filter((name) => !before.has(name));
    const removed = [...before.keys()].filter((name) => !after.has(name));
    return {
        changed, added, removed,
        lines: [...changed.map((name) => `  ~ ${name}`), ...added.map((name) => `  + ${name}`), ...removed.map((name) => `  - ${name}`)],
        summary: `${changed.length} changed, ${added.length} added, ${removed.length} removed (${after.size - changed.length - added.length} unchanged)`,
    };
};

/** Each entry of the contract type in a printed module, as its own text followed by every declaration it reaches. Empty when the text holds no such type. */
const entryClosures = (ts: TypeScriptModule, typeName: string, text: string): Map<string, string> => {
    const sourceFile = ts.createSourceFile("contract.ts", text, ts.ScriptTarget.Latest, true);
    const declared = new Map<string, ts.TypeNode>();
    let contract: ts.TypeLiteralNode | undefined;
    for(const statement of sourceFile.statements){
        if(!ts.isTypeAliasDeclaration(statement)) continue;
        if(statement.name.text === typeName && ts.isTypeLiteralNode(statement.type)) contract = statement.type;
        else declared.set(statement.name.text, statement.type);
    }
    const closures = new Map<string, string>();
    for(const member of contract?.members ?? []){
        if(!ts.isPropertySignature(member) || !member.type || !(ts.isIdentifier(member.name) || ts.isStringLiteral(member.name))) continue;
        const reached = new Set<string>();
        const visit = (node: ts.Node) => {
            if(ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)){
                const name = node.typeName.text;
                const body = declared.get(name);
                if(body && !reached.has(name)){
                    reached.add(name);
                    visit(body);
                }
            }
            ts.forEachChild(node, visit);
        };
        visit(member.type);
        closures.set(member.name.text, [member.type.getText(sourceFile), ...[...reached].sort().map((name) => `type ${name} = ${declared.get(name)!.getText(sourceFile)}`)].join("\n"));
    }
    return closures;
};

const formatDiagnostics = (ts: TypeScriptModule, diagnostics: readonly ts.Diagnostic[]): string[] => {
    const shown = ts.formatDiagnostics(diagnostics.slice(0, DIAGNOSTIC_LIMIT), {
        getCanonicalFileName: (fileName) => fileName,
        getCurrentDirectory: () => process.cwd(),
        getNewLine: () => "\n",
    }).trim().split("\n").map((line) => `  ${line}`);
    return diagnostics.length > DIAGNOSTIC_LIMIT ? [...shown, `  ... and ${diagnostics.length - DIAGNOSTIC_LIMIT} more`] : shown;
};
