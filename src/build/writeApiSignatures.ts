import { spawnSync } from "child_process";
import { existsSync, mkdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import type { LambderApiSignatureEntry } from "../api/LambderApiSignature.js";
import type { FreshProcessRequest, FreshProcessVerdict } from "./freshProcessVerifier.js";

/*
 * The signature file every app with apiSignatures needs, written and checked
 * by the framework that defines it.
 *
 * The digests are computed once, by the generator, into this file, and both
 * sides read the file: the frontend hands it to LambderCaller and the server
 * hands it to create(), so the two can never disagree. What can still go wrong is the file itself (stale against the
 * registrations, or different in every process because a schema reads the
 * clock), and both are checked here.
 */

/**
 * How the fresh process reports its comparison: one line on stdout starting
 * with this, then the verdict as JSON. The line, not the exit status, is the
 * answer: the app's module prints what it likes while it loads, and a
 * process that fails before the line never compared anything.
 */
export const VERIFY_REPORT_PREFIX = "lambder-api-signatures-verified:";

/** How long a fresh-process verification may run before it counts as failed. */
const VERIFY_TIMEOUT_MS = 5 * 60 * 1000;

/** What a fresh process may print before its verdict line: a chatty module must not fill the pipe and fail the check. */
const VERIFY_OUTPUT_BYTES = 64 * 1024 * 1024;

/** The fresh process's entry, beside this module in the build. */
const FRESH_PROCESS_ENTRY = new URL("./freshProcessVerifier.js", import.meta.url);

/**
 * This process's own Node flags that the fresh process must not inherit,
 * because they make it something other than a plain run of the verifier: the
 * inspector (`--inspect-brk` waits for a debugger forever, and a fixed port
 * collides with this process's), watch mode (a watched process never exits),
 * the test runner (`--test` runs the entry as a test file), and the eval
 * flags: `-e`, `-p` and a cluster of them such as `-pe` (which run their code
 * in place of the entry), and `--input-type` (which Node refuses beside an
 * entry file). Everything else, `--import`, `--require`, `--loader`,
 * `--conditions` and the rest, is how this process loads the app's modules,
 * and the fresh one needs it to load the same way.
 */
const PARENT_ONLY_FLAG = /^(--(inspect|debug-port|watch|test)([-=].*)?|--(eval|print|input-type)(=.*)?|-[a-z]*[ep][a-z]*)$/;

/** This process's execArgv, less the flags only it may run with (see PARENT_ONLY_FLAG). */
export const freshProcessNodeFlags = (execArgv: readonly string[]): string[] => {
    const kept: string[] = [];
    for(let index = 0; index < execArgv.length; index++){
        const flag = execArgv[index]!;
        if(!PARENT_ONLY_FLAG.test(flag)){
            kept.push(flag);
            continue;
        }
        // execArgv holds only Node's own options (the script and its
        // arguments are argv), so an element that is not a flag is the value
        // of the flag before it, and goes with it.
        const next = execArgv[index + 1];
        if(!flag.includes("=") && next !== undefined && !next.startsWith("-")) index++;
    }
    return kept;
};

const DEFAULT_HEADER = [
    "Generated by writeApiSignatures() from lambder/build. Do not edit.",
    "",
    "Every API the server registers, keyed by the hash of its name, with the",
    "digest of its client-facing shape. The client sends the value with every",
    "call and the server compares it with its own copy of this file, so a",
    "deploy reloads only the tabs that call an endpoint whose shape changed.",
].join("\n");

/** What writeApiSignatures reads the signatures from: a Lambder instance, or anything else that lists them the same way. */
export type LambderApiSignatureSource = {
    apiSignatureEntries(): Promise<LambderApiSignatureEntry[]>;
};

export type LambderApiSignatureFileOptions = {
    /** The TypeScript module to write, exporting `apiSignatures`. Relative to the working directory. */
    file: string;
    /** Write nothing, and answer whether the file on disk is what the registrations produce now. Default: false. */
    check?: boolean;
    /** The comment the file opens with, one `//` line per line. It should name what generates the file. Default: a note naming writeApiSignatures(). */
    header?: string;
    /** Quotes in the generated module. Default: "double". */
    quotes?: "single" | "double";
    /** End the generated statements with semicolons. Default: true. */
    semicolons?: boolean;
    /**
     * After writing, or after a check that found the file current, load the
     * module that holds the instance in a fresh Node process and check the
     * file against what it digests there. A schema built from the clock or a
     * random source digests differently in every process; this catches it by
     * endpoint name instead of letting signatures change on every build. Only
     * that module is loaded, never the calling script, so nothing the script
     * does runs twice; the module's own top-level code does run again. The
     * fresh process gets this process's Node flags (`--import`, `--require`,
     * `--loader`, `--conditions`) less the inspector, watch mode, the test
     * runner and the eval flags (`-e`, `-p`, `--input-type`), so a TypeScript
     * module loads there as it did here when its loader is on the command
     * line or in NODE_OPTIONS. Default: not verified.
     */
    verifyInFreshProcess?: {
        /**
         * The module that exports the instance: a path relative to the
         * working directory, or a file URL, as a URL such as
         * `new URL("../backend/index.js", import.meta.url)` beside the
         * generator's own import of it, or as the string
         * `import.meta.resolve()` answers.
         */
        module: string | URL;
        /** The export that holds the instance. Default: "default", the module's default export. */
        exportName?: string;
    };
};

export type LambderApiSignatureFileResult = {
    /** False when a check found the file stale, or a fresh process digested different signatures or never compared them. */
    ok: boolean;
    /** The absolute path. */
    file: string;
    /** How many APIs the file holds. */
    count: number;
    /** True when the file was (re)written; a file that already holds these signatures is left untouched, however it is formatted. */
    written: boolean;
    /** Endpoints whose signature differs from the file that was on disk, by name. */
    changed: string[];
    added: string[];
    /** Endpoints the file held and the registrations no longer have. Named by key only: a key is a one-way hash of a name that is gone. */
    removedKeys: string[];
    /** What happened, as lines to print: a summary, then one line per endpoint that moved. */
    lines: string[];
};

/**
 * The map a generated file holds, read back by its hex pairs. Either quote
 * style parses, and so does a key without quotes: a formatter that quotes
 * properties only as needed (Prettier's default, Biome's, ESLint's
 * quote-props) unquotes every key that starts with a letter.
 */
export const readSignatureMap = (contents: string): Record<string, string> => {
    const map: Record<string, string> = {};
    for(const match of contents.matchAll(/(?<![\w$])(['"]?)([0-9a-f]+)\1\s*:\s*['"]([0-9a-f]+)['"]/g)) map[match[2]!] = match[3]!;
    return map;
};

/** How the registrations differ from a map read off a file, by endpoint, as the lines both this process and a fresh one print. */
export const describeSignatureChanges = (entries: LambderApiSignatureEntry[], previousMap: Record<string, string>) => {
    const byName = (a: LambderApiSignatureEntry, b: LambderApiSignatureEntry) => a.name.localeCompare(b.name);
    const changed = entries.filter(({ key, signature }) => key in previousMap && previousMap[key] !== signature).sort(byName).map(({ name }) => name);
    const added = entries.filter(({ key }) => !(key in previousMap)).sort(byName).map(({ name }) => name);
    const keys = new Set(entries.map(({ key }) => key));
    const removedKeys = Object.keys(previousMap).filter((key) => !keys.has(key));
    const movedLines = [
        ...changed.map((name) => `  ~ ${name}`),
        ...added.map((name) => `  + ${name}`),
        ...removedKeys.map((key) => `  - ${key} (removed: a key cannot be resolved back to its name)`),
    ];
    const summary = `${changed.length} changed, ${added.length} added, ${removedKeys.length} removed (${entries.length - changed.length - added.length} unchanged)`;
    return { changed, added, removedKeys, movedLines, summary };
};

const renderSignatureFile = (entries: LambderApiSignatureEntry[], options: LambderApiSignatureFileOptions): string => {
    const quote = options.quotes === "single" ? "'" : "\"";
    const semicolon = options.semicolons === false ? "" : ";";
    const header = (options.header ?? DEFAULT_HEADER).split("\n").map((line) => line ? `// ${line}` : "//");
    // Keys and signatures are hex, so swapping the quote character touches nothing inside them.
    const map = JSON.stringify(Object.fromEntries(entries.map(({ key, signature }) => [key, signature])), null, 4).replace(/"/g, quote);
    return [
        ...header,
        `import type { LambderApiSignatureMap } from ${quote}lambder/client${quote}${semicolon}`,
        "",
        // Kept as written by a formatter that honours it, so a format pass
        // after every generation has nothing to change. One that does not
        // honour it changes the text only: the map reads back the same.
        "// prettier-ignore",
        `export const apiSignatures: LambderApiSignatureMap = ${map}${semicolon}`,
        "",
    ].join("\n");
};

/**
 * Writes the signature map both sides ship (see Lambder.apiSignatures()) to
 * a TypeScript module, or checks the one on disk, and says which endpoints
 * moved: every changed signature is a forced reload for the tabs calling
 * that endpoint, so this is the line that says how wide a deploy's reload
 * will be.
 *
 * Call it from a generator script that imports the app's instance:
 *
 * ```ts
 * import { writeApiSignatures } from "lambder/build";
 * import { lambder } from "../server/src/index.js";
 *
 * const result = await writeApiSignatures(lambder, { file: "shared/generated/apiSignatures.generated.ts", check: process.argv.includes("--check") });
 * console.log(result.lines.join("\n"));
 * process.exit(result.ok ? 0 : 1);
 * ```
 *
 * Signatures are compared as the map the file holds, so a checkout that
 * rewrote its line endings or a formatter that re-indented it or unquoted
 * its keys is neither stale nor rewritten. `verifyInFreshProcess` also
 * checks the file, written or found current, against the instance's module
 * loaded in a fresh process.
 */
export const writeApiSignatures = async (
    source: LambderApiSignatureSource,
    options: LambderApiSignatureFileOptions,
): Promise<LambderApiSignatureFileResult> => {
    const file = resolve(options.file);
    const entries = await source.apiSignatureEntries();
    const previous = existsSync(file) ? readFileSync(file, "utf8") : null;
    const { changed, added, removedKeys, movedLines, summary } = describeSignatureChanges(entries, previous === null ? {} : readSignatureMap(previous));
    const unchanged = previous !== null && movedLines.length === 0;
    const result = (ok: boolean, written: boolean, lines: string[]): LambderApiSignatureFileResult =>
        ({ ok, file, count: entries.length, written, changed, added, removedKeys, lines });

    // A stale file is the answer by itself: a fresh process could only find
    // it stale again. A current one goes on to the verification, as a write
    // does, so a check that names verifyInFreshProcess verifies.
    let written = false;
    let lines: string[];
    if(options.check){
        if(!unchanged) return result(false, false, [`✗ ${options.file} is stale: regenerate it`, `  ${summary}`, ...movedLines]);
        lines = [`✓ ${options.file} matches the ${entries.length} registered APIs`];
    }else{
        // A file that already holds this map is left as it is, however it is
        // formatted, so a watcher or an incremental build sees no change
        // where there is none, and a formatter's or a checkout's version of
        // the file is not rewritten back on every run. A change of header,
        // quotes or semicolons shows the next time the map changes. The write
        // goes to a file beside the target and is renamed over it, so a build
        // reading the file meanwhile sees the old map or the new one, never
        // half of one. A symlink is followed to the file it names: renamed
        // over, the link itself would become the new file and its target
        // would keep the old map.
        written = !unchanged;
        if(written){
            const target = previous === null ? file : realpathSync(file);
            mkdirSync(dirname(target), { recursive: true });
            const partial = `${target}.${process.pid}.tmp`;
            try {
                writeFileSync(partial, renderSignatureFile(entries, options));
                renameSync(partial, target);
            } catch(err) {
                rmSync(partial, { force: true });
                throw err;
            }
        }
        lines = [
            written ? `✓ Wrote ${options.file} (${entries.length} APIs)` : `✓ ${options.file} is up to date (${entries.length} APIs)`,
            ...(movedLines.length ? [`  ${summary}`, ...movedLines] : ["  no signatures changed: this build forces no reloads"]),
        ];
    }
    if(!options.verifyInFreshProcess) return result(true, written, lines);

    const { module: instanceModule, exportName = "default" } = options.verifyInFreshProcess;
    const request: FreshProcessRequest = {
        // A string that is already a file URL (what import.meta.resolve()
        // answers) is taken as one: resolved as a path, it would name a
        // directory called "file:" under the working directory.
        moduleUrl: typeof instanceModule === "string" && !/^file:/i.test(instanceModule)
            ? pathToFileURL(resolve(instanceModule)).href
            : new URL(instanceModule).href,
        exportName,
        file,
    };
    const child = spawnSync(process.execPath, [...freshProcessNodeFlags(process.execArgv), fileURLToPath(FRESH_PROCESS_ENTRY), JSON.stringify(request)], {
        encoding: "utf8",
        timeout: VERIFY_TIMEOUT_MS,
        maxBuffer: VERIFY_OUTPUT_BYTES,
    });
    const reportLine = (child.stdout ?? "").split("\n").findLast((line) => line.startsWith(VERIFY_REPORT_PREFIX));
    if(reportLine === undefined){
        const stderrTail = (child.stderr ?? "").trim().split("\n").slice(-20).filter(Boolean);
        return result(false, written, [
            ...lines,
            child.error
                ? `✗ the fresh process that verifies ${options.file} could not finish: ${child.error.message}`
                : `✗ the fresh process that verifies ${options.file} never compared it: loading ${request.moduleUrl} failed (exit status ${child.status ?? "none"})`,
            ...stderrTail.map((line) => `  ${line}`),
        ]);
    }
    const verdict = JSON.parse(reportLine.slice(VERIFY_REPORT_PREFIX.length)) as FreshProcessVerdict;
    if("failure" in verdict) return result(false, written, [...lines, `✗ the fresh process that verifies ${options.file} never compared it: ${verdict.failure}`]);
    if(verdict.same) return result(true, written, [...lines, "✓ a fresh process digests the same signatures"]);
    return result(false, written, [
        ...lines,
        `✗ a fresh process digests different signatures for ${options.file}: a schema reads the clock or a random source`,
        ...verdict.lines.map((line) => `  ${line}`),
    ]);
};
