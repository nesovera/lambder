import { existsSync, readFileSync } from "fs";
import { resolve } from "path";
import type { LambderApiOptionEntries } from "../shared/wire/LambderApiOptionEntries.js";
import type { LambderModuleLocation } from "./moduleLocation.js";
import {
    headerLinesOf,
    loadApiOptionEntries,
    nameChangesOf,
    readGeneratedTable,
    settleGeneratedFile,
    tableStatementLines,
    type LambderNameChanges,
} from "./generatedTables.js";

/*
 * The declared options of an app's APIs as a generated module of plain data:
 * every API's mode and its guards, rateLimit and idempotency options as
 * written, every rate-limit policy less its key handler, and every guard's
 * input mode, session flag and place in the call. The contract already
 * carries the options as types; this is the same fact as a value, for the
 * code that decides something at runtime with it: a mock restating the
 * server's declarations, a test walking the public surface. Neither imports
 * the server for it. The file names every endpoint, so a production bundle
 * imports none of it: a screen that gates on a guard reads that guard's
 * parameters alone (writeApiGuardParams).
 *
 * Plain data by construction: the instance refuses to report a guard
 * parameter that is code or a class instance (see Lambder.apiOptionEntries),
 * a policy's key handler is reduced to `per: "custom"`, and a guard's schema
 * to its input mode. No secret can reach the file, because nothing that could
 * hold one is written.
 */

const DEFAULT_HEADER = [
    "Generated by writeApiOptions() from lambder/build. Do not edit.",
    "",
    "Every API the server registers with its declared options, every rate-limit",
    "policy less its key handler, and every guard's input mode: the server's",
    "declarations as plain data, for the code that decides something with them",
    "without importing the server.",
].join("\n");

/** The three tables the module exports, in the order they are written. */
const TABLES = [
    { name: "apiOptions", key: "apis", type: "LambderApiOptionEntry", doc: "Every API the server registers: its mode and its guards, rateLimit and idempotency options as written." },
    { name: "rateLimitPolicies", key: "rateLimitPolicies", type: "LambderRateLimitPolicyEntry", doc: "Every rate-limit policy the server declares, its key reduced to what it counts: an address, a session, or a key the app derives (\"custom\")." },
    { name: "guardDeclarations", key: "guards", type: "LambderGuardDeclarationEntry", doc: "Every guard the server declares: how it is fed, whether it needs a session, and when it runs." },
] as const satisfies readonly { name: string; key: keyof LambderApiOptionEntries; type: string; doc: string }[];

type TableKey = keyof LambderApiOptionEntries;

export type LambderApiOptionsFileOptions = {
    /**
     * The module that exports the instance, usually the server's entry: a
     * path relative to the working directory, or a file URL. It is imported
     * in this process, so a TypeScript module needs the process's loader
     * (`tsx`, `node --import tsx`), as the generator script itself does.
     */
    module: LambderModuleLocation;
    /** The export that holds the instance. Default: "default", the module's default export. */
    exportName?: string;
    /** The TypeScript module to write, exporting `apiOptions`, `rateLimitPolicies` and `guardDeclarations`. Relative to the working directory. */
    file: string;
    /** Write nothing, and answer whether the file on disk holds what the instance reports now. Default: false. */
    check?: boolean;
    /** The comment the file opens with, one `//` line per line. It should name what generates the file. Default: a note naming writeApiOptions(). */
    header?: string;
    /** End the generated statements with semicolons. Default: true. The tables themselves are JSON, double quotes included, whatever the project's style: that is what lets a check read them back. */
    semicolons?: boolean;
};

export type LambderApiOptionsFileResult = {
    /** False when a check found the file stale or unreadable. */
    ok: boolean;
    /** The absolute path. */
    file: string;
    /** True when the file was (re)written; a file that already holds these tables is left untouched, however it is formatted. */
    written: boolean;
    /** How many APIs, policies and guards the tables hold. */
    counts: Record<TableKey, number>;
    /** What moved, per table, against the file that was on disk. */
    changes: Record<TableKey, LambderNameChanges>;
    /** What happened, as lines to print: a summary, then one line per name that moved. */
    lines: string[];
};

/** The tables a generated file holds, read back as data, or null for a file that does not hold all three as written (never written, or rewritten by hand). */
export const readOptionTables = (contents: string): LambderApiOptionEntries | null => {
    const tables: Partial<Record<TableKey, Record<string, unknown>>> = {};
    for(const table of TABLES){
        const read = readGeneratedTable(contents, table.name);
        if(!read) return null;
        tables[table.key] = read;
    }
    return tables as LambderApiOptionEntries;
};

const renderOptionsFile = (entries: LambderApiOptionEntries, options: LambderApiOptionsFileOptions): string => {
    const semicolon = options.semicolons === false ? "" : ";";
    return [
        ...headerLinesOf(options.header ?? DEFAULT_HEADER),
        `import type { ${TABLES.map((table) => table.type).join(", ")} } from "lambder/client"${semicolon}`,
        ...TABLES.flatMap((table) => [
            "",
            ...tableStatementLines({ name: table.name, doc: table.doc, value: entries[table.key], satisfies: `Record<string, ${table.type}>`, semicolon }),
        ]),
        "",
    ].join("\n");
};

/**
 * Writes the declared options of an app's APIs as a module of plain data, or
 * checks the one on disk, and says which APIs, policies and guards moved.
 *
 * Call it from a generator script beside writeApiSignatures, naming the
 * module that exports the app's instance:
 *
 * ```ts
 * import { writeApiOptions } from "lambder/build";
 *
 * const result = await writeApiOptions({
 *     module: "server/src/index.ts",   // export const lambder = initLambder()...
 *     exportName: "lambder",
 *     file: "shared/generated/apiOptions.generated.ts",
 *     check: process.argv.includes("--check"),
 * });
 * console.log(result.lines.join("\n"));
 * process.exit(result.ok ? 0 : 1);
 * ```
 *
 * The tables are compared as the data the file holds, so a checkout that
 * rewrote its line endings or a formatter that re-indented it is neither
 * stale nor rewritten, and a file whose data is current is left as it is.
 * There is no fresh-process check: nothing here is digested, so nothing can
 * differ per process. A module that does not load, an export that is not an
 * instance, or a guard parameter that is not plain data throws.
 */
export const writeApiOptions = async (options: LambderApiOptionsFileOptions): Promise<LambderApiOptionsFileResult> => {
    const file = resolve(options.file);
    const entries = await loadApiOptionEntries(options, "writeApiOptions");
    const previousText = existsSync(file) ? readFileSync(file, "utf8") : null;
    const previous = previousText === null ? null : readOptionTables(previousText);
    const changes = Object.fromEntries(TABLES.map((table) => [table.key, nameChangesOf(entries[table.key], previous?.[table.key] ?? {})])) as Record<TableKey, LambderNameChanges>;
    const counts = Object.fromEntries(TABLES.map((table) => [table.key, Object.keys(entries[table.key]).length])) as Record<TableKey, number>;
    const settled = settleGeneratedFile({
        name: options.file, file, check: options.check, previousText, readBack: previous !== null,
        tables: TABLES.map((table) => ({ name: table.name, count: counts[table.key], changes: changes[table.key] })),
        held: `${counts.apis} APIs, ${counts.rateLimitPolicies} policies, ${counts.guards} guards`,
        tablesNoun: "the three tables",
        unmovedLine: "no options changed",
        render: () => renderOptionsFile(entries, options),
    });
    return { ...settled, file, counts, changes };
};
