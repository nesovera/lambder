import { existsSync, readFileSync } from "fs";
import { resolve } from "path";
import { z } from "zod";
import { canonicalJson } from "../shared/util/canonicalJson.js";
import { LAMBDER_STRIP_UNKNOWN_KEYS, type LambderApiSchemaEntry, type LambderJsonSchema } from "../shared/wire/LambderApiSchemaEntries.js";
import { moduleUrlOf, type LambderModuleLocation } from "./moduleLocation.js";
import { headerLinesOf, nameChangesOf, settleGeneratedFile, tableStatementLines, type LambderNameChanges } from "./generatedTables.js";

/*
 * Every API's input and output schemas as JSON Schema, in a generated module
 * of plain data a mock validates its calls against: so in development an
 * endpoint refuses what the server refuses (a length, a format, a range), a
 * handler reads the payload the server's parse leaves, and an answer goes out
 * stripped and defaulted as the server sends it.
 *
 * The input is written in its input form, what the server's parse takes from
 * a client. The output is written in its output form, because a mock handler
 * returns what the client receives (the contract types it so), where a server
 * handler returns what the schema parses from: the output form is what the
 * mock has to check and strip.
 *
 * z.toJSONSchema writes the schemas, and three things are this writer's own.
 * A zod object drops the keys it does not declare, which JSON Schema cannot
 * say, so each such object is marked (LAMBDER_STRIP_UNKNOWN_KEYS) and the mock
 * drops them again. What zod cannot represent at all (a Date, a bigint, a Map)
 * throws, naming the API and the place, since a schema the mock reads
 * differently from the server is the drift this file exists to end. And what
 * zod represents only in part is listed as a loss, in the result and its
 * lines: a refinement it leaves out, a transform it does not run, a pipe whose
 * second schema the input form does not carry, a default a function computes
 * on each parse, a check it writes without what zod runs it with (a regex's
 * flags, a URL's protocol rule). Where zod writes a check the mock would read
 * back as another (a guid as a strict uuid, a custom email pattern as zod's
 * own), the writer leaves out the misleading part instead.
 *
 * The file names every endpoint and every field each takes and gives, so it
 * is for development alone: imported by the mock's setup, which a production
 * build never loads.
 */

const DEFAULT_HEADER = [
    "Generated by writeApiSchemas() from lambder/build. Do not edit.",
    "",
    "Every API's input schema, in the form a client posts, and output schema,",
    "in the form a client receives, as JSON Schema (draft 2020-12): what the",
    "mock validates its calls against, as the server does. Development only:",
    "it names every endpoint, so only the mock's setup imports it.",
].join("\n");

const TABLE_NAME = "apiSchemas";

/** The zod schemas of one API, as a source reports them. */
type LambderApiSchemaPair = { input: z.ZodType; output: z.ZodType };

/** What writeApiSchemas reads the schemas from: a Lambder instance, or anything else that reports them the same way. */
export type LambderApiSchemasSource = {
    /** Every API's input and output schemas by name. Asynchronous, since a Lambder instance loads its lazy groups before it can report every endpoint. */
    apiSchemaEntries(): Promise<Record<string, LambderApiSchemaPair>> | Record<string, LambderApiSchemaPair>;
};

/**
 * One place where an API's schema does something its written JSON Schema
 * cannot hold, so the mock does not do it either:
 *
 * - `refinement`: a `.refine()`, `.superRefine()` or `.check()` check, or a
 *   `z.custom()` schema (written as one that takes anything). The mock does
 *   not run it, so it lets through what the refinement refuses.
 * - `transform`: a `.transform()` (in the output form written as a schema
 *   that takes anything), a `z.preprocess()`, a codec, a rewrite such as
 *   `.trim()` or `.toLowerCase()`, a `z.coerce` schema, a `.catch()`. The mock
 *   does not apply it: its handler reads the value as posted, and a coerced or
 *   caught input the server takes, the mock refuses.
 * - `pipe`: the second schema of a `.pipe()`. The input form carries the
 *   first, so the mock does not check the second.
 * - `default`: a default a function computes on each parse, which the file
 *   cannot hold, so it is left out and the mock fills nothing there.
 * - `check`: a string check JSON Schema cannot state as zod runs it: a regex
 *   with flags (`/i`, `/u`), whose pattern means something else without
 *   them, or a URL's `protocol` or `hostname` rule (`z.httpUrl()` among
 *   them). The mock does not run it, so it lets through what the check
 *   refuses.
 */
export type LambderApiSchemaLoss = {
    /** The API whose schema it is. */
    api: string;
    /** Which of its schemas: the input a client posts, or the output it receives. */
    direction: "input" | "output";
    /** Where, as a JSON pointer into the written schema: `#/properties/name`, or `#` for the whole schema. */
    path: string;
    kind: "refinement" | "transform" | "pipe" | "default" | "check";
};

export type LambderApiSchemasFileOptions = {
    /**
     * The module that exports the instance, usually the server's entry: a
     * path relative to the working directory, or a file URL. It is imported
     * in this process, so a TypeScript module needs the process's loader
     * (`tsx`, `node --import tsx`), as the generator script itself does.
     */
    module: LambderModuleLocation;
    /** The export that holds the instance. Default: "default", the module's default export. */
    exportName?: string;
    /** The TypeScript module to write, exporting `apiSchemas`. Relative to the working directory. */
    file: string;
    /** Write nothing, and answer whether the file on disk holds what the instance reports now. Default: false. */
    check?: boolean;
    /** The comment the file opens with, one `//` line per line. It should name what generates the file and say it is for development only. Default: a note naming writeApiSchemas(). */
    header?: string;
    /** End the generated statement with a semicolon. Default: true. The table itself is JSON, double quotes included, whatever the project's style: that is what lets a check read it back. */
    semicolons?: boolean;
};

export type LambderApiSchemasFileResult = {
    /** False when a check found the file stale or unreadable. Losses do not make it false: they are what the file cannot hold, however current it is. */
    ok: boolean;
    /** The absolute path. */
    file: string;
    /** True when the file was (re)written; a file that already holds this table is left untouched, however it is formatted. */
    written: boolean;
    /** How many APIs the table holds. */
    count: number;
    /** Which APIs moved against the file that was on disk. */
    changes: LambderNameChanges;
    /** Every place a schema does what its written form cannot hold, sorted by API, direction and place. */
    losses: LambderApiSchemaLoss[];
    /** What happened, as lines to print: a summary, one line per API that moved, then one line per loss. */
    lines: string[];
};

/** What each kind of loss says in the lines. */
const LOSS_WORDING: Record<LambderApiSchemaLoss["kind"], string> = {
    refinement: "a refinement, which the mock does not run",
    transform: "a transform, which the mock does not apply",
    pipe: "a pipe, whose second schema the mock does not check",
    default: "a default computed on each parse, which the mock does not fill",
    check: "a check written without its flags or URL rule, which the mock does not run",
};

/** A check's definition, with the fields a string format check (`string_format`) carries. */
type InspectedCheckDef = { check: string; format?: string; pattern?: RegExp; protocol?: RegExp; hostname?: RegExp; normalize?: boolean };

/** The parts of a zod schema's definition the writer reads, whatever the schema's type. A format schema (z.email()) is a check itself, so it carries a check's fields too. */
type InspectedDef = Partial<InspectedCheckDef> & {
    type: string;
    catchall?: unknown;
    checks?: readonly { _zod: { def: InspectedCheckDef } }[];
    coerce?: boolean;
    in?: z.core.$ZodType;
    out?: z.core.$ZodType;
    transform?: unknown;
    defaultValue?: unknown;
    catchValue?: (ctx: unknown) => unknown;
};

const defOf = (schema: z.core.$ZodType): InspectedDef => schema._zod.def as unknown as InspectedDef;

/**
 * Regex flags that change what a pattern matches. A JSON Schema pattern is
 * the source alone, so the mock compiles it without them; `g` and `d` change
 * nothing about a test zod runs from the start of the value.
 */
const MEANING_FLAGS = /[imsuvy]/;

/** zod's own email pattern, which the mock rebuilds a written `format: "email"` with. */
const DEFAULT_EMAIL_PATTERN = (z.email()._zod.def as InspectedCheckDef).pattern!;

/** A JSON pointer into the written schema, for a path as z.toJSONSchema reports it. */
const pointerOf = (path: readonly (string | number)[]): string =>
    ["#", ...path.map((segment) => String(segment).replace(/~/g, "~0").replace(/\//g, "~1"))].join("/");

/** A value as the JSON it is written as, compared by data: what the file holds of a default. */
const asWritten = (value: unknown): string | undefined => {
    const text = JSON.stringify(value);
    return text === undefined ? undefined : canonicalJson(JSON.parse(text));
};

/**
 * Whether the default zod wrote is computed on each parse: read once more,
 * it answers otherwise. A default given as a value is copied on each read and
 * answers the same; one a function computes (an id, a timestamp) would put a
 * different value in the file on every run, and a value the server never
 * repeats in every mock call.
 */
const computedOnEachParse = (def: InspectedDef, written: unknown): boolean => {
    let again: unknown;
    try {
        again = def.type === "catch" ? def.catchValue?.(undefined) : def.defaultValue;
    } catch {
        return true;
    }
    return asWritten(again) !== asWritten(written);
};

/**
 * Whether zod cannot represent a schema because of what it does to a value
 * rather than what it takes: a transform, a z.custom(), a catch whose value is
 * computed from the failed parse, a coercion (z.coerce.date() parses to a
 * Date, which JSON Schema has no type for). Each is written as a schema that
 * takes anything and listed as a loss; anything else zod cannot represent
 * throws.
 */
const isNonCarryable = (def: InspectedDef): boolean =>
    def.type === "transform" || def.type === "custom" || def.type === "catch" || def.coerce === true;

/** One API's schema in the direction given, as plain JSON Schema, with what it does not carry added to `losses`. */
const jsonSchemaOf = (api: string, direction: "input" | "output", schema: z.ZodType, losses: LambderApiSchemaLoss[]): LambderJsonSchema => {
    if(typeof (schema as { _zod?: unknown } | undefined)?._zod !== "object"){
        throw new Error(`writeApiSchemas: API "${api}" reports no zod ${direction} schema.`);
    }
    const lose = (path: readonly (string | number)[], kind: LambderApiSchemaLoss["kind"]) => {
        const loss: LambderApiSchemaLoss = { api, direction, path: pointerOf(path), kind };
        if(!losses.some((known) => known.api === loss.api && known.direction === loss.direction && known.path === loss.path && known.kind === loss.kind)) losses.push(loss);
    };
    const written = z.toJSONSchema(schema, {
        io: direction,
        unrepresentable: ({ zodSchema, path, message }) => {
            const def = defOf(zodSchema);
            if(!isNonCarryable(def)){
                throw new Error(`writeApiSchemas: the ${direction} schema of API "${api}" holds what JSON Schema cannot represent, at ${pointerOf(path)}: ${message}. Declare it as the value it is on the wire (a z.date() as z.iso.datetime(), a bigint as a string).`);
            }
            lose(path, def.type === "custom" ? "refinement" : "transform");
            return "any";
        },
        override: ({ zodSchema, jsonSchema, path }) => {
            const def = defOf(zodSchema);
            const json = jsonSchema as Record<string, unknown>;
            if(def.type === "object" && def.catchall === undefined){
                // zod writes nothing in the input form and false in the
                // output form, where the parse accepts the key and drops it.
                delete json.additionalProperties;
                json[LAMBDER_STRIP_UNKNOWN_KEYS] = true;
            }
            for(const check of def.checks ?? []){
                if(check._zod.def.check === "custom") lose(path, "refinement");
                else if(check._zod.def.check === "overwrite") lose(path, "transform");
            }
            if(def.type === "string"){
                // The mock rebuilds a written format by its name, with zod's
                // defaults (a guid as a strict uuid, an email under zod's
                // own pattern), and the pattern written beside it as given.
                const formatChecks = [def, ...(def.checks ?? []).map((check) => check._zod.def)].filter((check) => check.check === "string_format");
                for(const check of formatChecks){
                    // The pattern written beside these is the check exactly;
                    // the format would read back stricter than the server.
                    if(check.format === "guid" || (check.format === "email" && (check.pattern?.source !== DEFAULT_EMAIL_PATTERN.source || check.pattern.flags !== DEFAULT_EMAIL_PATTERN.flags))) delete json.format;
                    if(check.format === "url"){
                        if(check.protocol || check.hostname) lose(path, "check");
                        if(check.normalize) lose(path, "transform");
                    }
                    if(check.pattern && MEANING_FLAGS.test(check.pattern.flags)){
                        // Without its flags the pattern refuses what the
                        // server takes, so it is not written. A format the
                        // mock rebuilds by name (z.emoji()) still runs it.
                        const source = check.pattern.source;
                        if(json.pattern === source) delete json.pattern;
                        if(Array.isArray(json.allOf)){
                            json.allOf = (json.allOf as Record<string, unknown>[]).filter((entry) => entry.pattern !== source);
                            if(!(json.allOf as unknown[]).length) delete json.allOf;
                        }
                        if(check.format === "regex" || !("format" in json)) lose(path, "check");
                    }
                }
                // A string's second pattern goes in allOf, and the mock reads
                // an allOf entry's pattern only when the entry says string.
                for(const entry of Array.isArray(json.allOf) ? json.allOf as Record<string, unknown>[] : []){
                    if("pattern" in entry) entry.type = "string";
                }
            }
            if(def.type === "custom") lose(path, "refinement");
            if(def.type === "transform") lose(path, "transform");
            // A coercion, a catch and a pipe change only what an input may
            // be: a mock handler returns its output already in the form the
            // client receives, which the output form checks in full.
            if(direction === "input"){
                if(def.coerce === true || def.type === "catch") lose(path, "transform");
                if(def.type === "pipe"){
                    const transforms = def.in?._zod.def.type === "transform" || def.out?._zod.def.type === "transform" || def.transform !== undefined;
                    lose(path, transforms ? "transform" : "pipe");
                }
            }
            if((def.type === "default" || def.type === "prefault" || def.type === "catch") && "default" in json && computedOnEachParse(def, json.default)){
                delete json.default;
                lose(path, "default");
            }
        },
    });
    // Through JSON, so what the file holds is exactly the plain data a check
    // reads back; the draft is the module's, said once in its header.
    const plain = JSON.parse(JSON.stringify(written)) as Record<string, unknown>;
    delete plain.$schema;
    return plain;
};

/** Losses in a stable order, so the lines and the result read the same on every run. */
const compareLosses = (a: LambderApiSchemaLoss, b: LambderApiSchemaLoss): number =>
    a.api.localeCompare(b.api) || a.direction.localeCompare(b.direction) || a.path.localeCompare(b.path) || a.kind.localeCompare(b.kind);

/** The losses as lines, under one naming how many APIs carry them. */
const lossLinesOf = (losses: readonly LambderApiSchemaLoss[]): string[] => {
    if(!losses.length) return [];
    const apis = new Set(losses.map((loss) => loss.api)).size;
    return [
        `  ${apis === 1 ? "1 API carries" : `${apis} APIs carry`} what JSON Schema cannot hold, which the mock does not check:`,
        ...losses.map((loss) => `  ! ${loss.api} ${loss.direction} ${loss.path}: ${LOSS_WORDING[loss.kind]}`),
    ];
};

/**
 * The table a generated file holds, read back as data, or null for a file
 * that does not hold it as written. Read up to the last `as const` in the
 * file, which is the statement's own: the file holds one statement, and a
 * schema's description may say "as const" itself.
 */
const readSchemaTable = (contents: string): Record<string, unknown> | null => {
    const match = new RegExp(`export const ${TABLE_NAME}\\s*=\\s*([\\s\\S]*)\\s+as const\\b`).exec(contents);
    if(!match) return null;
    try {
        const table: unknown = JSON.parse(match[1]!);
        return table !== null && typeof table === "object" && !Array.isArray(table) ? table as Record<string, unknown> : null;
    } catch {
        return null;
    }
};

const renderSchemasFile = (entries: Record<string, LambderApiSchemaEntry>, options: LambderApiSchemasFileOptions): string => [
    ...headerLinesOf(options.header ?? DEFAULT_HEADER),
    "",
    ...tableStatementLines({
        name: TABLE_NAME,
        doc: "Every API the server registers: its input schema in its input form and its output schema in its output form, as JSON Schema.",
        value: entries,
        semicolon: options.semicolons === false ? "" : ";",
    }),
    "",
].join("\n");

/** Imports the module, finds the instance under its export, and answers the schemas it reports. */
const loadApiSchemaPairs = async (options: LambderApiSchemasFileOptions): Promise<Record<string, LambderApiSchemaPair>> => {
    const moduleUrl = moduleUrlOf(options.module);
    const exportName = options.exportName ?? "default";
    let namespace: Record<string, unknown>;
    try {
        namespace = await import(moduleUrl) as Record<string, unknown>;
    } catch(err) {
        throw new Error(`writeApiSchemas could not load ${moduleUrl}`, { cause: err });
    }
    const source = namespace[exportName] as Partial<LambderApiSchemasSource> | null | undefined;
    if(typeof source?.apiSchemaEntries !== "function"){
        throw new Error(`${moduleUrl} has no export "${exportName}" that reports API schemas: name the export holding the instance in exportName`);
    }
    return await source.apiSchemaEntries();
};

/**
 * Writes every API's input and output schemas as JSON Schema to a module of
 * plain data, or checks the one on disk, and says which APIs moved and what
 * their schemas do that the file cannot hold.
 *
 * Call it from a generator script beside writeApiOptions, writing to where
 * the mock's setup reads it:
 *
 * ```ts
 * import { writeApiSchemas } from "lambder/build";
 *
 * const result = await writeApiSchemas({
 *     module: "server/src/index.ts",   // export const lambder = initLambder()...
 *     exportName: "lambder",
 *     file: "web/src/mock/apiSchemas.generated.ts",
 *     check: process.argv.includes("--check"),
 * });
 * console.log(result.lines.join("\n"));
 * process.exit(result.ok ? 0 : 1);
 * ```
 *
 * The table is compared as the data the file holds, so a checkout that
 * rewrote its line endings or a formatter that re-indented it is neither
 * stale nor rewritten. The same instance writes the same file on every run.
 * A module that does not load, an export that is not an instance, or a
 * schema holding what JSON Schema cannot represent (other than a refinement
 * or a transform, which are listed) throws.
 */
export const writeApiSchemas = async (options: LambderApiSchemasFileOptions): Promise<LambderApiSchemasFileResult> => {
    const file = resolve(options.file);
    const pairs = await loadApiSchemaPairs(options);
    const losses: LambderApiSchemaLoss[] = [];
    const entries: Record<string, LambderApiSchemaEntry> = {};
    for(const api of Object.keys(pairs).sort()){
        const pair = pairs[api]!;
        entries[api] = { input: jsonSchemaOf(api, "input", pair.input, losses), output: jsonSchemaOf(api, "output", pair.output, losses) };
    }
    losses.sort(compareLosses);
    const previousText = existsSync(file) ? readFileSync(file, "utf8") : null;
    const previous = previousText === null ? null : readSchemaTable(previousText);
    const changes = nameChangesOf(entries, previous ?? {});
    const count = Object.keys(entries).length;
    const settled = settleGeneratedFile({
        name: options.file, file, check: options.check, previousText, readBack: previous !== null,
        tables: [{ name: TABLE_NAME, count, changes }],
        held: count === 1 ? "1 API" : `${count} APIs`,
        tablesNoun: "the schema table",
        unmovedLine: "no schemas changed",
        render: () => renderSchemasFile(entries, options),
    });
    return { ...settled, lines: [...settled.lines, ...lossLinesOf(losses)], file, count, changes, losses };
};
