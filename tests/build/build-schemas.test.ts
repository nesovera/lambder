/**
 * lambder/build: every API's input and output schemas as JSON Schema, in a
 * generated module of plain data the mock validates its calls against. What
 * the instance reports, what the writer writes for each kind of schema, what
 * it lists as not carried and what it refuses, and that a check finds drift
 * and nothing else.
 *
 * Files are written under the system's temporary directory, never into the
 * repository; the fixture's own generated module is only checked.
 */

import { afterAll, describe, expect, it } from 'vitest';
import { z } from 'zod';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { generateApiFiles, writeApiSchemas, type LambderApiSchemasFileOptions } from '../../src/build.js';
import { LAMBDER_STRIP_UNKNOWN_KEYS } from '../../src/shared/wire/LambderApiSchemaEntries.js';
import { placeOrderOutput, shopApp } from '../fixtures/schema-app/shop.js';

const directory = mkdtempSync(join(tmpdir(), 'lambder-schemas-'));
afterAll(() => rmSync(directory, { recursive: true, force: true }));

let fileCount = 0;
const nextFile = () => join(directory, `apiSchemas-${fileCount++}.generated.ts`);

const SHOP = 'tests/fixtures/schema-app/shop.ts';
const SOURCES = 'tests/fixtures/schema-app/sources.ts';

const writeShop = (options: Omit<LambderApiSchemasFileOptions, 'module' | 'exportName'>) =>
    writeApiSchemas({ module: SHOP, exportName: 'shopApp', ...options });

/** The table a written file holds, imported as the mock's setup imports it. */
const tableIn = async (file: string): Promise<Record<string, { input: any; output: any }>> =>
    (await import(`${pathToFileURL(file).href}?read=${fileCount++}`) as { apiSchemas: Record<string, { input: any; output: any }> }).apiSchemas;

describe('Lambder.apiSchemaEntries', () => {
    it('reports every API sorted by name, with the schemas it was declared with', async () => {
        const entries = await shopApp.apiSchemaEntries();

        expect(Object.keys(entries)).toEqual(['catalog.update', 'orders.place', 'stores.search', 'tickets.open']);
        expect(entries['orders.place']!.output).toBe(placeOrderOutput);
    });
});

describe('writeApiSchemas', () => {
    it('writes a module of plain data: no import, one table, the header saying it is for development', async () => {
        const file = nextFile();
        const result = await writeShop({ file });

        expect(result).toMatchObject({ ok: true, written: true, count: 4, changes: { changed: [], added: ['catalog.update', 'orders.place', 'stores.search', 'tickets.open'], removed: [] } });
        const text = readFileSync(file, 'utf8');
        expect(text).not.toMatch(/^import /m);
        expect(text.startsWith('// Generated by writeApiSchemas() from lambder/build. Do not edit.\n')).toBe(true);
        expect(text).toContain('Development only');
        expect(text).toMatch(/^export const apiSchemas = \{$/m);
        expect(text.trimEnd().endsWith('} as const;')).toBe(true);

        const table = await tableIn(file);
        expect(Object.keys(table)).toEqual(['catalog.update', 'orders.place', 'stores.search', 'tickets.open']);
        expect(table['orders.place']!.input.$schema).toBeUndefined();
    });

    it('writes lengths, formats, ranges and enums as JSON Schema keywords', async () => {
        const file = nextFile();
        await writeShop({ file });
        const { input } = (await tableIn(file))['orders.place']!;

        expect(input.properties.customer.properties.name).toEqual({ type: 'string', minLength: 2, maxLength: 40 });
        expect(input.properties.customer.properties.email).toMatchObject({ type: 'string', format: 'email' });
        expect(input.properties.items).toMatchObject({ type: 'array', minItems: 1, maxItems: 5 });
        expect(input.properties.items.items.properties.quantity).toEqual({ type: 'integer', minimum: 1, maximum: 10 });
        expect(input.properties.items.items.properties.sku).toEqual({ type: 'string', pattern: '^[A-Z]{3}-\\d{3}$' });
        expect(input.properties.delivery).toEqual({ type: 'string', enum: ['pickup', 'courier'] });
        expect(input.properties.payment.oneOf).toHaveLength(2);
    });

    it('writes the input in its input form and the output in its output form', async () => {
        const file = nextFile();
        await writeShop({ file });
        const table = await tableIn(file);

        // What a client may leave out of an input: the optional field and the
        // defaulted one, which the parse fills.
        const order = table['orders.place']!;
        expect(order.input.required).toEqual(['customer', 'items', 'delivery', 'payment']);
        expect(order.input.properties.giftWrap).toEqual({ type: 'boolean', default: false });
        // What a client always receives: a defaulted field is there.
        expect(order.output.required).toContain('courierNote');
        expect(order.output.properties.courierNote).toEqual({ type: 'string', default: 'Leave it with the doorman' });
    });

    it('marks every object that drops undeclared keys, in both forms, and leaves a strict and a loose one as zod writes them', async () => {
        const file = nextFile();
        await writeShop({ file });
        const table = await tableIn(file);

        // z.object(): zod writes nothing in the input form and false in the
        // output form; both are written as the mark, with nothing refused.
        for(const form of [table['orders.place']!.input, table['orders.place']!.output]){
            expect(form[LAMBDER_STRIP_UNKNOWN_KEYS]).toBe(true);
            expect(form.additionalProperties).toBeUndefined();
        }
        expect(table['orders.place']!.input.properties.customer[LAMBDER_STRIP_UNKNOWN_KEYS]).toBe(true);
        expect(table['orders.place']!.output.properties.lines.items[LAMBDER_STRIP_UNKNOWN_KEYS]).toBe(true);
        // A recursive schema is written once, under $defs, marked there.
        const update = table['catalog.update']!.input;
        expect(update.$defs.__schema0[LAMBDER_STRIP_UNKNOWN_KEYS]).toBe(true);
        // z.strictObject refuses other keys; z.looseObject keeps them.
        expect(update.properties.product.additionalProperties).toBe(false);
        expect(update.properties.product[LAMBDER_STRIP_UNKNOWN_KEYS]).toBeUndefined();
        expect(update.properties.tags.additionalProperties).toEqual({});
        expect(update.properties.tags[LAMBDER_STRIP_UNKNOWN_KEYS]).toBeUndefined();
        // An intersection keeps both of its sides, each dropping what it does not declare.
        expect(update.properties.price.allOf.map((side: Record<string, unknown>) => side[LAMBDER_STRIP_UNKNOWN_KEYS])).toEqual([true, true]);
    });

    it('writes the same file on every run, and leaves a current file untouched', async () => {
        const first = nextFile();
        const second = nextFile();
        await writeShop({ file: first });
        await writeShop({ file: second });
        expect(readFileSync(second, 'utf8')).toBe(readFileSync(first, 'utf8'));

        const again = await writeShop({ file: first });
        expect(again).toMatchObject({ ok: true, written: false });
        expect(again.lines[0]).toBe(`✓ ${first} is up to date (4 APIs)`);
        expect(again.lines[1]).toBe('  no schemas changed');
    });

    it('checks the file on disk: current, and current however it was reformatted', async () => {
        const file = nextFile();
        await writeShop({ file });

        const current = await writeShop({ file, check: true });
        expect(current).toMatchObject({ ok: true, written: false });
        expect(current.lines[0]).toBe(`✓ ${file} matches the 4 APIs`);

        writeFileSync(file, readFileSync(file, 'utf8').replace(/\n/g, '\r\n').replace(/ {4}/g, '\t'));
        expect(await writeShop({ file, check: true })).toMatchObject({ ok: true });
    });

    it('finds drift: a schema that moved names its API, and a file rewritten by hand is not read as current', async () => {
        const file = nextFile();
        await writeShop({ file });

        const moved = await writeApiSchemas({ module: SOURCES, exportName: 'widerNames', file, check: true });
        expect(moved).toMatchObject({ ok: false, written: false, changes: { changed: ['orders.place'], added: [], removed: [] } });
        expect(moved.lines.slice(0, 3)).toEqual([
            `✗ ${file} is stale: regenerate it`,
            '  apiSchemas: 1 changed, 0 added, 0 removed (3 unchanged)',
            '  ~ apiSchemas orders.place',
        ]);

        writeFileSync(file, readFileSync(file, 'utf8').replace('export const apiSchemas = {', 'export const apiSchemas: object = {'));
        const unreadable = await writeShop({ file, check: true });
        expect(unreadable.ok).toBe(false);
        expect(unreadable.lines[0]).toBe(`✗ ${file} does not hold the schema table as written: regenerate it`);
    });

    it('lists every refinement and transform it cannot carry, by API, direction and place', async () => {
        const result = await writeShop({ file: nextFile() });

        expect(result.losses).toEqual([
            { api: 'tickets.open', direction: 'input', path: '#/properties/seat', kind: 'refinement' },
            { api: 'tickets.open', direction: 'input', path: '#/properties/subject', kind: 'transform' },
            { api: 'tickets.open', direction: 'output', path: '#/properties/seat', kind: 'transform' },
        ]);
        expect(result.lines.slice(-4)).toEqual([
            '  1 API carries what JSON Schema cannot hold, which the mock does not check:',
            '  ! tickets.open input #/properties/seat: a refinement, which the mock does not run',
            '  ! tickets.open input #/properties/subject: a transform, which the mock does not apply',
            '  ! tickets.open output #/properties/seat: a transform, which the mock does not apply',
        ]);
        // In a check too, since what is not carried is as true of a current file.
        expect((await writeShop({ file: nextFile(), check: true })).lines.at(-1)).toBe('  ! tickets.open output #/properties/seat: a transform, which the mock does not apply');
    });

    it('handles each kind of schema zod carries only in part, as zod writes it', async () => {
        const file = nextFile();
        const result = await writeApiSchemas({ module: SOURCES, exportName: 'partlyCarried', file });
        const at = (path: string) => ({ api: 'tickets.book', path });

        expect(result.losses).toEqual([
            // A catch, a coercion (a coerced Date has no JSON Schema at all),
            // a codec, a preprocess, a transform and a rewrite change what an
            // input may be; the mock takes the input as posted.
            { ...at('#/properties/caught'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/checked'), direction: 'input', kind: 'refinement' },
            { ...at('#/properties/coded'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/coerced'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/coercedDate'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/computedId'), direction: 'input', kind: 'default' },
            { ...at('#/properties/custom'), direction: 'input', kind: 'refinement' },
            { ...at('#/properties/piped'), direction: 'input', kind: 'pipe' },
            { ...at('#/properties/preprocessed'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/refined'), direction: 'input', kind: 'refinement' },
            { ...at('#/properties/transformed'), direction: 'input', kind: 'transform' },
            { ...at('#/properties/trimmed'), direction: 'input', kind: 'transform' },
            // A mock handler returns the output as the client receives it, so
            // a pipe, a coercion and a catch change nothing there; a
            // refinement, a transform and a rewrite do.
            { ...at('#/properties/refined'), direction: 'output', kind: 'refinement' },
            { ...at('#/properties/transformed'), direction: 'output', kind: 'transform' },
            { ...at('#/properties/trimmed'), direction: 'output', kind: 'transform' },
        ]);

        const { input, output } = (await tableIn(file))['tickets.book']!;
        // What zod cannot represent at all is written as a schema that takes anything.
        expect(input.properties.custom).toEqual({});
        expect(input.properties.coercedDate).toEqual({});
        expect(output.properties.transformed).toEqual({});
        // What it can, the side it can: the source of a transform, the first
        // schema of an input's pipe and the second of an output's, a codec's
        // encoded side in and its decoded side out.
        expect(input.properties.transformed).toEqual({ type: 'string' });
        expect(input.properties.piped).toEqual({ type: 'string' });
        expect(output.properties.piped).toEqual({ type: 'string', minLength: 2 });
        expect(input.properties.coded).toEqual({ type: 'string' });
        expect(input.properties.preprocessed).toEqual({ type: 'string' });
        // A default a function computes on each parse is left out; one it
        // answers the same with is held.
        expect(input.properties.computedId).toEqual({ type: 'string' });
        expect(input.properties.emptyList).toMatchObject({ type: 'array', default: [] });
        // And the file is the same on the next run, the computed default included.
        expect((await writeApiSchemas({ module: SOURCES, exportName: 'partlyCarried', file, check: true })).ok).toBe(true);
    });

    it('never writes a string check the mock reads back stricter than the server, and lists the ones it cannot carry', async () => {
        const file = nextFile();
        const result = await writeApiSchemas({ module: SOURCES, exportName: 'stringChecks', file });
        const at = (path: string) => ({ api: 'stores.register', direction: 'input', path, kind: 'check' });

        // A regex with flags means something else without them, and a URL's
        // protocol rule has no keyword: the mock does not run either.
        expect(result.losses).toEqual([at('#/properties/code'), at('#/properties/contact'), at('#/properties/name'), at('#/properties/website')]);

        const { input } = (await tableIn(file))['stores.register']!;
        const server = (await import('../fixtures/schema-app/sources.js')).stringChecks.apiSchemaEntries()['stores.register'].input.shape;
        const tried: Record<string, string[]> = {
            code: ['NYC', 'ny1'],
            name: ['Café', 'Shop 1'],
            sku: ['A1', 'a1', 'AB'],
            website: ['https://shop.example.com', 'ftp://shop.example.com'],
            receiptId: ['12345678-1234-1234-1234-123456789012', 'not-a-guid'],
            contact: ['zoë@example.com', 'no-at-sign'],
            badge: ['🍕', 'a'],
        };
        for(const [field, values] of Object.entries(tried)){
            const mock = z.fromJSONSchema(input.properties[field]);
            for(const value of values){
                const serverTakes = server[field as keyof typeof server].safeParse(value).success;
                const mockTakes = mock.safeParse(value).success;
                // What it carries, it carries exactly; what it lists, it lets through.
                if(['sku', 'receiptId', 'badge'].includes(field)) expect([field, value, mockTakes]).toEqual([field, value, serverTakes]);
                else if(serverTakes) expect([field, value, mockTakes]).toEqual([field, value, true]);
            }
        }
    });

    it('throws, naming the API, the direction and the place, for what JSON Schema cannot represent', async () => {
        await expect(writeApiSchemas({ module: SOURCES, exportName: 'datedReceipts', file: nextFile() })).rejects.toThrow(
            'writeApiSchemas: the output schema of API "receipts.get" holds what JSON Schema cannot represent, at #/properties/issuedAt: Date cannot be represented in JSON Schema.',
        );
    });

    it('throws for a module that does not load or an export that reports no schemas', async () => {
        await expect(writeApiSchemas({ module: join(directory, 'missing.mjs'), file: nextFile() })).rejects.toThrow(/^writeApiSchemas could not load .*missing\.mjs$/);
        await expect(writeApiSchemas({ module: SHOP, exportName: 'placeOrderOutput', file: nextFile() })).rejects.toThrow(/has no export "placeOrderOutput" that reports API schemas/);
    });

    it('keeps the fixture module the mock tests import current', async () => {
        const result = await writeShop({ file: 'tests/fixtures/schema-app/apiSchemas.generated.ts', check: true });
        expect(result.lines[0]).toBe('✓ tests/fixtures/schema-app/apiSchemas.generated.ts matches the 4 APIs');
        expect(result.ok).toBe(true);
    });
});

describe('generateApiFiles with schemas', () => {
    it('writes an app\'s schemas beside its other files, and checks them', async () => {
        const file = nextFile();
        const config = { apps: { shop: { module: SHOP, exportName: 'shopApp', schemas: { file } } } };

        const written = await generateApiFiles(config);
        expect(written.ok).toBe(true);
        expect(written.lines[0]).toBe(`✓ Wrote ${file} (4 APIs)`);
        expect(Object.keys(await tableIn(file))).toHaveLength(4);

        expect(await generateApiFiles(config, { check: true })).toMatchObject({ ok: true });
        await expect(generateApiFiles({ apps: { shop: { module: SHOP } } })).rejects.toThrow('give it a contract, signatures, options, guardParams or schemas');
    });

    it('reports a schema it cannot write beside the files it can', async () => {
        const result = await generateApiFiles({ apps: { receipts: { module: SOURCES, exportName: 'datedReceipts', schemas: { file: nextFile() } } } });
        expect(result.ok).toBe(false);
        expect(result.lines).toEqual([expect.stringMatching(/^✗ receipts: the schemas failed: writeApiSchemas: the output schema of API "receipts.get"/)]);
    });
});
